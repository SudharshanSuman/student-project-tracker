import { createReadStream } from "node:fs";
import { access } from "node:fs/promises";
import { Router } from "express";
import type { GeneratedReport, Prisma } from "@prisma/client";
import { createReportSchema, REPORT_TYPE_LABELS } from "@iic/shared";
import { prisma } from "../db.js";
import { projectAccess } from "../lib/access.js";
import { audit } from "../lib/audit.js";
import { conflict, forbidden, HttpError, notFound } from "../lib/errors.js";
import { parse, uuidParam } from "../lib/validate.js";
import { currentUser, requireAuth, requireRole, type AuthUser } from "../middleware/auth.js";
import { kickReportWorker } from "../reports/queue.js";
import { deleteReportFile, reportPath } from "../reports/storage.js";

/**
 * PDF reports (staff only). Requests enqueue a job and return 202 immediately; the background
 * worker renders the PDF. Report content is scoped to what the requester can see at generation
 * time (mentors: their mentored projects; admins: everything). Downloads re-check authorization
 * on every request and are refused after expiry.
 */
export const reportsRouter = Router();
// Mounted at /api/reports so the staff-only guard never touches other routes.
reportsRouter.use(requireAuth, requireRole("ADMIN", "MENTOR"));

const MAX_OPEN_JOBS_PER_USER = 5;

const reportInclude = { requestedBy: { select: { id: true, name: true } }, project: { select: { id: true, name: true } } } satisfies Prisma.GeneratedReportInclude;

function view(r: Prisma.GeneratedReportGetPayload<{ include: typeof reportInclude }>) {
  const expired = !!r.expiresAt && r.expiresAt < new Date();
  const { storageKey, ...rest } = r; // never expose storage paths
  return { ...rest, downloadable: r.status === "COMPLETED" && !!storageKey && !expired, expired };
}

/** Admin: any report. Mentor: only their own, and only while they can still see its project. */
async function loadReport(user: AuthUser, id: string): Promise<GeneratedReport> {
  const report = await prisma.generatedReport.findUnique({ where: { id } });
  if (!report) throw notFound("Report not found");
  if (user.role === "ADMIN") return report;
  if (report.requestedById !== user.id) throw notFound("Report not found");
  if (report.projectId && !(await projectAccess(user, report.projectId))) throw notFound("Report not found");
  return report;
}

reportsRouter.get("/", async (req, res) => {
  const user = currentUser(req);
  const reports = await prisma.generatedReport.findMany({
    where: user.role === "ADMIN" ? {} : { requestedById: user.id },
    include: reportInclude,
    orderBy: { createdAt: "desc" },
    take: 100,
  });
  const [projects, cohorts] = await Promise.all([
    prisma.project.findMany({ where: user.role === "ADMIN" ? {} : { mentorId: user.id }, select: { id: true, name: true }, orderBy: { name: "asc" } }),
    prisma.cohort.findMany({ select: { id: true, name: true, term: true, startDate: true, endDate: true }, orderBy: { name: "asc" } }),
  ]);
  res.json({ reports: reports.map(view), projects, cohorts, isAdmin: user.role === "ADMIN" });
});

reportsRouter.post("/", async (req, res) => {
  const user = currentUser(req);
  const input = parse(createReportSchema, req.body);
  if (input.type === "EXECUTIVE_SUMMARY" && user.role !== "ADMIN") throw forbidden("Executive summaries are generated by admins");
  let scopeName = user.role === "ADMIN" ? "All projects" : "Mentored projects";
  if (input.projectId) {
    const a = await projectAccess(user, input.projectId);
    if (!a) throw notFound("Project not found");
    scopeName = a.project.name;
  }
  if (input.cohortId) {
    const cohort = await prisma.cohort.findUnique({ where: { id: input.cohortId }, select: { name: true } });
    if (!cohort) throw notFound("Cohort not found");
    scopeName = input.projectId ? scopeName : `Cohort ${cohort.name}`;
  }
  const open = await prisma.generatedReport.count({ where: { requestedById: user.id, status: { in: ["QUEUED", "RUNNING"] } } });
  if (open >= MAX_OPEN_JOBS_PER_USER) throw new HttpError(429, "You already have several reports in progress; wait for them to finish", "TOO_MANY_REPORTS");
  const period = input.periodStart && input.periodEnd ? ` (${input.periodStart} to ${input.periodEnd})` : "";
  const report = await prisma.$transaction(async (tx) => {
    const r = await tx.generatedReport.create({
      data: {
        type: input.type,
        title: `${REPORT_TYPE_LABELS[input.type]}: ${scopeName}${period}`.slice(0, 200),
        projectId: input.projectId ?? null,
        periodStart: input.periodStart ? new Date(`${input.periodStart}T00:00:00.000Z`) : null,
        periodEnd: input.periodEnd ? new Date(`${input.periodEnd}T00:00:00.000Z`) : null,
        parameters: { cohortId: input.cohortId ?? null, projectId: input.projectId ?? null },
        requestedById: user.id,
      },
      include: reportInclude,
    });
    await audit(req, { action: "report.requested", entityType: "GeneratedReport", entityId: r.id, projectId: r.projectId, metadata: { type: r.type, title: r.title } }, tx);
    return r;
  });
  kickReportWorker();
  res.status(202).json({ report: view(report) });
});

reportsRouter.get("/:id", async (req, res) => {
  const report = await loadReport(currentUser(req), uuidParam(req.params.id));
  res.json({ report: view(await prisma.generatedReport.findUniqueOrThrow({ where: { id: report.id }, include: reportInclude })) });
});

reportsRouter.get("/:id/download", async (req, res) => {
  const user = currentUser(req);
  const report = await loadReport(user, uuidParam(req.params.id));
  if (report.status !== "COMPLETED") throw conflict("This report is not ready", "NOT_READY");
  if (!report.storageKey || (report.expiresAt && report.expiresAt < new Date())) throw new HttpError(410, "This report has expired; generate it again", "EXPIRED");
  const file = reportPath(report.storageKey);
  try {
    await access(file);
  } catch {
    throw new HttpError(410, "The report file is no longer available; generate it again", "EXPIRED");
  }
  await audit(req, { action: "report.downloaded", entityType: "GeneratedReport", entityId: report.id, projectId: report.projectId });
  const safeName = report.title.replace(/[^A-Za-z0-9 ._()-]+/g, "").replace(/\s+/g, "_").slice(0, 120) || "report";
  res.setHeader("Content-Type", "application/pdf");
  res.setHeader("Content-Disposition", `attachment; filename="${safeName}.pdf"`);
  res.setHeader("Cache-Control", "private, no-store");
  res.setHeader("X-Content-Type-Options", "nosniff");
  if (report.sizeBytes) res.setHeader("Content-Length", String(report.sizeBytes));
  createReadStream(file).pipe(res);
});

reportsRouter.post("/:id/retry", async (req, res) => {
  const user = currentUser(req);
  const report = await loadReport(user, uuidParam(req.params.id));
  if (report.status !== "FAILED") throw conflict("Only failed reports can be retried", "NOT_FAILED");
  const updated = await prisma.generatedReport.update({ where: { id: report.id }, data: { status: "QUEUED", attempts: 0, error: null, nextAttemptAt: null }, include: reportInclude });
  await audit(req, { action: "report.retried", entityType: "GeneratedReport", entityId: report.id, projectId: report.projectId });
  kickReportWorker();
  res.json({ report: view(updated) });
});

reportsRouter.delete("/:id", async (req, res) => {
  const user = currentUser(req);
  const report = await loadReport(user, uuidParam(req.params.id));
  if (report.status === "RUNNING") throw conflict("This report is being generated; try again in a moment", "RUNNING");
  await prisma.generatedReport.delete({ where: { id: report.id } });
  await deleteReportFile(report.storageKey);
  await audit(req, { action: "report.deleted", entityType: "GeneratedReport", entityId: report.id, projectId: report.projectId, metadata: { title: report.title } });
  res.status(204).end();
});
